}

// 通用：统计区间内指定星期几的次数
// 直接按公式计算，不逐日循环（区间再长也是 O(1)）
function count_weekday_between(string $start_date, string $end_date, int $targetDow): int
{
  $start = new \DateTime($start_date);
  $end   = new \DateTime($end_date);
  if ($start > $end) return 0;

  $days   = (int) $start->diff($end)->days + 1;                       // 区间总天数（含首尾）
  $offset = ($targetDow - (int) $start->format('w') + 7) % 7;         // 距第一个目标星期几还有几天
  if ($offset >= $days) return 0;
  return intdiv($days - 1 - $offset, 7) + 1;
}

// CSV 转义
function csv_escape($value): string
{
  $v = (string)$value;
  // Allow the explicit Excel-text wrapper generated by csv_excel_text(), e.g. ="+614..."
  $is_excel_text_wrapper = (bool) preg_match('/^=".*"$/', $v);
  if (!$is_excel_text_wrapper && preg_match('/^[-+=@].*/', $v)) {
    $v = "'" . $v; // 防 CSV 注入
  }
  $v = str_replace('"', '""', $v);
  return '"' . $v . '"';
}

// Excel-safe phone text (avoid scientific notation)
function csv_excel_text($value): string
{
  $v = trim((string) $value);
  if ($v === '') {
    return '';
  }
  return '="' . str_replace('"', '""', $v) . '"';
}

