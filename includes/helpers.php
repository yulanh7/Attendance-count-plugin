}

function format_date_dmy(?string $s): string
{
  if (!$s) return '';
  // 先试通用 strtotime
  $ts = strtotime($s);
  if ($ts !== false && $ts > 0) return date('d/m/Y', $ts);

  // 再精确按两种常见格式解析
  $fmts = ['Y-m-d', 'd/m/Y', 'Y/m/d', 'd-m-Y'];
  foreach ($fmts as $fmt) {
    $dt = \DateTime::createFromFormat($fmt, $s);
    if ($dt) return $dt->format('d/m/Y');
  }
  return '';
}

// 认识途径的显示文字（按界面语言）
function ap_translate_referral_source($key, string $lang = 'zh_CN'): string
{
  $key = trim((string) $key);
  if ($key === '') {
    return I18n::t('referral_none', $lang);
  }
  if (in_array($key, ['family', 'friends', 'internet', 'walk_in', 'other'], true)) {
    return I18n::t('referral_' . $key, $lang);
  }
  return $key;
}

