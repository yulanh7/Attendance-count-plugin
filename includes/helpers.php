// 压缩 shortcode 输出的空白：防止宿主编辑器（wpautop、Elementor 文本编辑器等）
// 把标签间的空行/换行误判成段落，插入多余的 <p>/<br>，打乱 flex 布局
function ap_compact_html(string $html): string
{
  return trim(preg_replace('/>\s+</', '><', $html));
}

