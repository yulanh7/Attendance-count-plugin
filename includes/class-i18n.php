  /** @return array<string,string> */
  public static function table(string $lang): array
  {
    return self::STRINGS[$lang] ?? self::STRINGS['zh_CN'];
  }

  public static function t(string $key, string $lang, array $args = []): string
  {
    $s = self::table($lang)[$key] ?? $key;
    if (!$args) return $s;
    $map = [];
    foreach ($args as $k => $v) $map['{' . $k . '}'] = (string) $v;
    return strtr($s, $map);
  }

  /** @return string[] 注入到前端的 key */
  public static function js_keys(): array
  {
    $keys = array_filter(array_keys(self::STRINGS['zh_CN']), fn($k) => strpos($k, 'js_') === 0);
    return array_values(array_merge($keys, self::JS_SHARED));
  }
}

/** 按堂取文字 */
function t(string $key, string $congregation, array $args = []): string
{
  return I18n::t($key, Congregation::lang($congregation), $args);
